test('A: separat rapport importeres direkte fra risikooversikten og kan erstattes med integrert rapport', async ({ page }) => {
  await load(page)
  const risks = page.getByRole('region', { name: 'Forhold som påvirker valget.' })
  await page.locator('#overview-report-file').setInputFiles(fixture('separate-report-4.pdf'))
  await expect(risks.locator('.risk-report-upload')).toContainText('Dokumentuttrekk klart.')
  await risks.getByRole('button', { name: 'Se alle funn og kilder ↗' }).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog).toContainText('separate-report-4.pdf')
  await dialog.locator('.risk-finding > summary').first().click()
  await dialog.locator('.risk-finding').first().getByRole('button', { name: /Se originalkilde/ }).first().click()
  await expect(page.locator('.pdf-viewer')).toBeVisible()
  await expect(page.locator('.pdf-viewer')).toContainText('separate-report-4.pdf')
  await page.keyboard.press('Escape')
  await risks.getByRole('button', { name: 'Bruk integrert rapport igjen' }).click()
  await risks.getByRole('button', { name: 'Se alle funn og kilder ↗' }).click()
  await expect(dialog).toContainText('mixed-12.pdf')
  await expect(dialog).not.toContainText('separate-report-4.pdf')
  await page.keyboard.press('Escape')
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(risks).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})
