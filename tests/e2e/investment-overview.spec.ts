test('A: scenario endrer aldri kontrollert vurdering, TG3 eller resultatets snapshot', async ({ page }) => {
  await load(page); await assumptions(page)
  await page.getByTestId('open-financial-basis').click()
  for (const [field, value] of Object.entries({ P: '3200000', L: '252000', D: '48000', J: '164907.84', Ymin: '6' })) {
    await page.locator(`#value-${field}`).fill(value)
    await page.locator(`#source-kind-${field}`).selectOption('assumption')
    await page.locator(`#source-${field}`).fill(`Egen syntetisk testforutsetning ${field}`)
  }
  for (const field of ['L', 'D', 'J']) { await page.locator(`#period-${field}`).selectOption('year'); await page.locator(`#year-${field}`).fill('2026') }
  await page.locator('#rent-nature-L').selectOption('expected')
  await page.locator('#confirm-financial').click(); await page.locator('#next-step').click()
  await page.locator('#import-identity-check').check(); await page.locator('#import-area-check').check()
  await page.getByRole('button', { name: 'Gå til Kontroller funn', exact: true }).click()
  for (const row of await page.locator('.finding-list > li').all()) {
    await row.locator('.finding-select').click(); await row.getByRole('button', { name: 'Bekreft', exact: true }).click()
    if ((await row.locator('.finding-select').innerText()).startsWith('TG3')) await page.getByLabel('TG3-status for gjeldende forhold').selectOption('unresolved')
  }
  await page.getByRole('button', { name: 'Bekreft gjeldende liste', exact: true }).click()
  await page.getByRole('button', { name: 'Beregn og vis resultat', exact: true }).click()
  await expect(page.locator('#recommendation-title')).toHaveText('Innhent mer informasjon')
  const before = await page.locator('.screening-result').innerText()
  await page.getByRole('button', { name: '← Tilbake til investeringsoversikten' }).click()
  await page.locator('#scenario-equity').fill('1000000'); await page.locator('#scenario-rate').fill('9'); await page.locator('#scenario-years').fill('20')
  await expect(page.getByTestId('scenario-cash')).not.toHaveText('—', { timeout: 15_000 })
  await expect(page.locator('.assessment-copy')).toContainText('Innhent mer informasjon')
  await page.getByRole('button', { name: 'Se kontrollert vurdering ↗' }).click()
  expect(await page.locator('.screening-result').innerText()).toBe(before)
  await expect(page.locator('.result-tg3')).toContainText('Uavklart')
  await page.getByRole('button', { name: '← Tilbake til investeringsoversikten' }).click()
  await page.locator('#import-file-prospectus').evaluate((input: HTMLInputElement) => { const files = new DataTransfer(); files.items.add(new File([new ArrayBuffer(50 * 1024 * 1024 + 1)], 'for-stor.pdf', { type: 'application/pdf' })); input.files = files.files; input.dispatchEvent(new Event('change', { bubbles: true })) })
  await expect(page.locator('.assessment-copy')).not.toContainText('Innhent mer informasjon')
  await expect(page.locator('.risk-summary')).toContainText('TG-status ikke avklart')
  await expect(page.locator('#scenario-equity')).toHaveValue('')
})

