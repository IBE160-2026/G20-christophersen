    const visual = outcome.propertyRisk!.technical.findings.filter(item => item.sourceQuality === 'local-visual')
    expect(outcome.visualAnalysis?.pages.map(page => page.pdfPage)).toEqual(Array.from({ length: 25 }, (_, index) => index + 63))
